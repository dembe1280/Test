/* =========================================================
   BUSINESS STUDIES ANSWER FORMATTER
========================================================= */
function formatBusinessStudies(item, question) {
    const text = normalizeText(question);
    const parts = item.parts || {};
    const wanted = bsPartMap.filter(part => {
        if (!parts[part.key]) {
            return false;
        }
        return part.words.some(word => text.includes(word));
    });
    let html = `<h2>${escapeHtml(item.topic)}</h2>`;
    /* =====================================================
       IF NO SPECIFIC PART WAS ASKED
    ===================================================== */
    if (!wanted.length) {
        html += `
            <p>
                ${escapeHtml(item.information)}
            </p>
        `;
        if (item.rules && item.rules.length) {
            html += `
                <h3>Key Points</h3>
                <ul>
            `;
            item.rules.forEach(rule => {
                html += `
                    <li>
                        ${escapeHtml(rule)}
                    </li>
                `;
            });
            html += `</ul>`;
        }
    }
    /* =====================================================
       IF A SPECIFIC PART WAS ASKED
    ===================================================== */
    else {
        wanted.forEach(part => {
            html += `
                <h3>${escapeHtml(part.label)}</h3>
                <ul>
            `;
            parts[part.key].forEach(point => {
                html += `
                    <li>
                        ${escapeHtml(point)}
                    </li>
                `;
            });
            html += `</ul>`;
        });
    }
    /* =====================================================
       EXAMPLES
       Give stored examples for Business Studies.
    ===================================================== */
    const examples = (item.examples || []).slice(0, 10);
    if (examples.length) {
        html += `
            <h3>${examples.length} Examples</h3>
            <ol>
        `;
        examples.forEach(example => {
            html += `
                <li style="margin-bottom:6px;">
                    ${escapeHtml(example)}
                </li>
            `;
        });
        html += `</ol>`;
    }
    /* =====================================================
       STUDY TIP
    ===================================================== */
    if (!wanted.length) {
        html += `
            <p>
                <em>
                    Tip: You can ask specifically for the
                    purpose, advantages, disadvantages,
                    penalties, rights, examples, differences,
                    types, steps or ways to comply.
                </em>
            </p>
        `;
    }
    return html;
}
